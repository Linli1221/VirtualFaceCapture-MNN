#!/usr/bin/env node
/**
 * make-readme.mjs — 依据 manifest.json 重出 README.md 的哈希表
 *
 *   node windows-client/tools/evals/golden-export/make-readme.mjs
 *
 * 改动 renderer/ 或重跑 export-golden.mjs 之后，跑一次这个脚本刷新 README。
 */
import { readFileSync, writeFileSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const m = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8"));
const first = JSON.parse(readFileSync(join(dir, m.files[0].file), "utf8"));
const dim = first.meta.dimOrder;
const sha = (s) => createHash("sha256").update(s, "utf8").digest("hex");
const BT = String.fromCharCode(96); // markdown 反引号
const manifestText = readFileSync(join(dir, "manifest.json"), "utf8");

const L = [];
L.push("# golden-export —— 跨端黄金对拍数据集");
L.push("");
L.push("给 **Kotlin/JVM 侧**（android-raw，task-5）对拍用：用这些输入驱动 Kotlin 的");
L.push("BlendShapeExtractor / BlinkCurveProcessor，逐帧比对 expected，堵住");
L.push("「JS 参考实现只是第二份转录」的缺口——CI 里跑出来的是**真·Kotlin 输出**。");
L.push("");
L.push("## 生成命令");
L.push("");
L.push("    node windows-client/tools/evals/golden-export/export-golden.mjs");
L.push("    node windows-client/tools/evals/golden-export/make-readme.mjs");
L.push("");
L.push("生成器是确定性的：同样的源码版本重跑会得到同样的内容与 SHA-256。");
L.push("改动 `renderer/` 里的实现后**必须重跑并更新本 README 的哈希表**。");
L.push("");
L.push("## 校验哈希（SHA-256）");
L.push("");
L.push("拿走数据前请先核对，防止拷贝 / 换行 / 编码损坏：");
L.push("");
L.push("| 文件 | 帧数 | 字节 | sha256 |");
L.push("| --- | ---: | ---: | --- |");
for (const f of m.files) {
  L.push("| " + f.file + " | " + f.frameCount + " | " + f.bytes + " | " + BT + f.sha256 + BT + " |");
}
L.push("| manifest.json | - | " + Buffer.byteLength(manifestText) + " | " + BT + sha(manifestText) + BT + " |");
L.push("");
L.push("整目录校验（Node，跨平台）：");
L.push("");
L.push("    node windows-client/tools/evals/golden-export/verify.mjs");
L.push("");
L.push("## JSON 格式");
L.push("");
L.push("| 层级 | 字段 | 类型 | 含义 |");
L.push("| --- | --- | --- | --- |");
L.push("| 根 | scenario | string | 场景名 |");
L.push("| 根 | width / height | number | 画幅，固定 1280 / 720 |");
L.push("| 根 | frames | array | 逐帧数据，见下 |");
L.push("| 根 | meta | object | 口径、容差、下标序、编码、审计 |");
L.push("| frames[i] | t | number | 帧采集时间戳（ms），同时用作 nowMs 与 blink 时间戳 |");
L.push("| frames[i] | landmarks | string | base64(Float32Array little-endian)，478*3 = 1434 个浮点，x,y,z 交错 |");
L.push("| frames[i] | poseDeg | number[3] | 原始头姿 [pitch, yaw, roll]（度，未减基线） |");
L.push("| frames[i] | expectedBs52 | number[52] | extractFullBlendShapes 输出，含 blink 后的 [9]/[10] |");
L.push("| frames[i] | expectedBlinkOut | number[2] | BlinkCurveProcessor 输出 [left, right] |");
L.push("| meta | advancedMode | bool | 恒 false（第一阶段） |");
L.push("| meta | tolerance | object | abs 1e-4 / rel 1e-4（跨端，Lead 终裁） |");
L.push("| meta | dimOrder | string[52] | BS_INDEX 的 wire 顺序 |");
L.push("| meta | landmarkEncoding | object | 编码与 JVM 解码方式 |");
L.push("| meta | timing | object | nowMs / blink 时间戳的来源约定 |");
L.push("| meta | calibration | object | setCalibrationPoseCalled = false |");
L.push("| meta | jsInternalReferenceAgreement | number | JS 两份转录的最大差异（审计用） |");
L.push("");
L.push("### landmarks 解码（JVM）");
L.push("");
L.push("    ByteBuffer buf = ByteBuffer.wrap(Base64.getDecoder().decode(s)).order(ByteOrder.LITTLE_ENDIAN);");
L.push("    FloatBuffer fb = buf.asFloatBuffer();   // 长度 478*3 = 1434，x,y,z 交错");
L.push("");
L.push("归一化 [0,1]、y 向下、z 相对深度。**不要**在 JVM 侧重新生成几何——那是第三份转录。");
L.push("");
L.push("### expectedBs52 的语义");
L.push("");
L.push("- 顺序 = BS_INDEX（与 windows `renderer/mapping.js` 的 BS_INDEX 逐项相同）；");
L.push("- `advancedMode = false`：52 维里只有 17 维可能非零，其余恒 0；");
L.push("- `expectedBs52[9]` / `[10]` 已经是**眨眼曲线之后**的值（不是原始 eyeBlink）；");
L.push("- `expectedBlinkOut` 与 `[9]/[10]` 相同，单列一份便于直接对拍状态机。");
L.push("");
L.push("52 维下标顺序（wire order）：");
L.push("");
L.push("    " + dim.map((n, i) => i + "=" + n).join(", "));
L.push("");
L.push("## ⚠️ 必须遵守的口径");
L.push("");
L.push("| 项 | 值 | 为什么 |");
L.push("| --- | --- | --- |");
L.push("| 画幅 | 1280 x 720 | 像素转换是**各向异性**的（x*W / y*H），EAR/MAR 会带 H/W 因子；换画幅会大面积假阳性 |");
L.push("| advancedMode | false | Android 当前实际行为（`new BlendShapeExtractor()`） |");
L.push("| setCalibrationPose | **不调用** | 校准姿态保持各实现默认 0 |");
L.push("| nowMs | 用 `t` | fixture 约定；生产口径是 performance.now() |");
L.push("| blink 时间戳 | 用 `t` | 与生产口径一致 |");
L.push("| 起始帧率 | 30 fps（longDt 场景 3.333） | 眨眼确认帧数 `floor(2*33.3/interval)` 依赖它 |");
L.push("");
L.push("## ⚠️ 时间戳必须是整数毫秒（跨端对拍的必要口径）");
L.push("");
L.push("fixture 的 " + BT + "t" + BT + " 全部是**整数毫秒**，这不是格式偏好，是硬约束：");
L.push("");
L.push("- Kotlin 的 " + BT + "BlinkCurveProcessor.process(currentTimeMs: Long)" + BT + " 只收 Long；");
L.push("  若给小数 t（如 33.3333333），JS 侧 delta = 33.3333…、Kotlin 侧 delta = 33/34 交替，");
L.push("  眨眼曲线 " + BT + "curveProgress += deltaMs / duration" + BT + " 会逐步累积出 **~1e-2 量级**偏差，");
L.push("  是 1e-4 容差的百倍 —— 这不是实现差异，是时间量化差，必须从源头消除。");
L.push("- 同理，squint 的 300ms 严格比较、自校准的 1000ms 窗口都卡在边界上；");
L.push("  小数 t 会造成**整帧位移**（实测 longDt 场景 SQUINT_HOLD 提前/推迟一帧，输出差 0.5）。");
L.push("");
L.push("生成器用 " + BT + "Math.round(i * dtMs)" + BT + "（累计后取整，避免逐帧累加漂移），");
L.push("并在 " + BT + "export-golden.mjs" + BT + " 里加了整数断言，非整数直接抛错。");
L.push("");
L.push("JVM 侧请勿再做 " + BT + "t.roundToLong()" + BT + " 之类的二次处理 —— 落盘的就是最终值，");
L.push("直接用即可，保证两端消费**同一份整数时间线**（delta 序列逐位相同）。");
L.push("");
L.push("## 容差");
L.push("");
L.push("- **Kotlin ↔ JS 跨端**：abs 1e-4 / rel 1e-4（**Lead 终裁**）。断言写 " + BT + "|a-b| <= max(1e-4, 1e-4*|b|)" + BT + "；");
L.push("- **JS ↔ JS 内部**：abs 1e-5 / rel 1e-4（见 `tools/evals/golden-run.mjs`）。");
L.push("");
L.push("## 比对口径：请拆成两条统计");
L.push("");
L.push("1. **原始提取逐维误差**（blink 之前）—— 比对 `BlendShapeExtractor.extractFullBlendShapes` 的原始输出；");
L.push("2. **眨眼状态机输出误差** —— 比对 `BlinkCurveProcessor.process` 的输出。");
L.push("");
L.push("别合成一条：眨眼曲线在 TRACKING 态恒输出 0，会把提取差异盖住（这个坑我踩过）。");
L.push("为此 `expectedBs52` 里的 9/10 是 blink 后的值；若要单独比对原始 eyeBlink，");
L.push("请改用 `export-golden.mjs` 里的 `bs52Raw` 路径，或参考 `tools/evals/golden-run.mjs` 的写法。");
L.push("");
L.push("## 合成 fixture 的几何（便于 JVM 侧自检解码）");
L.push("");
L.push("| 量 | 值 |");
L.push("| --- | --- |");
L.push("| faceWidth = dist(33,263) | 0.28 |");
L.push("| faceHeight = dist(168,152) | 0.30 |");
L.push("| EAR(睁眼) | 0.18 |");
L.push("| EAR(闭眼) | 0.10 |");
L.push("| MAR(闭嘴) | 0.10 |");
L.push("| MAR(张大) | 0.45 |");
L.push("");
L.push("生成器：`windows-client/tools/evals/golden-fixtures.mjs`。JVM 侧**不必**重算这些，");
L.push("但要自检 base64 解码是否正确，这几条是最方便的探针。");
L.push("");
L.push("## 场景清单");
L.push("");
for (const f of m.files) L.push("- " + BT + f.file + BT + " — " + f.scenario);
L.push("");
L.push("## 审计：JS 两份转录的一致性");
L.push("");
L.push("每个 fixture 的 `meta.jsInternalReferenceAgreement` 是**JS 优化实现**与");
L.push("**JS 直译参考实现**（`golden-reference.mjs`）在整个场景上的最大逐维差异，");
L.push("当前全部为 **2.38e-7**，远在 1e-5 内。这个字段不是跨端指标，只是「基准本身可信」的旁证。");
L.push("");

writeFileSync(join(dir, "README.md"), L.join("\n"), "utf8");
console.log("README.md 已刷新，" + L.length + " 行");
